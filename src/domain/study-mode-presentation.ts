import type { StudyExperienceMode, StudySession } from './models';

export interface StudyModePresentation {
  id: StudyExperienceMode;
  label: string;
  description: string;
}

export const STUDY_MODE_PRESENTATIONS: Readonly<Record<StudyExperienceMode, StudyModePresentation>> = {
  anki: {
    id: 'anki',
    label: 'Spaced Review',
    description: 'Review due cards, with difficult cards returning again during the session when needed.',
  },
  mastery: {
    id: 'mastery',
    label: 'Confidence Study',
    description: 'Work through a scheduled queue and use confidence ratings to plan future reviews.',
  },
  'free-revision': {
    id: 'free-revision',
    label: 'Free Practice',
    description: 'Practise selected cards without changing their schedule or reward progress.',
  },
};

export const STUDY_MODE_OPTIONS: readonly StudyModePresentation[] = [
  STUDY_MODE_PRESENTATIONS.mastery,
  STUDY_MODE_PRESENTATIONS.anki,
  STUDY_MODE_PRESENTATIONS['free-revision'],
];

export function studyModePresentation(mode: StudyExperienceMode | undefined): StudyModePresentation {
  return STUDY_MODE_PRESENTATIONS[mode ?? 'mastery'];
}

const LEGACY_GENERATED_LABELS: Readonly<Partial<Record<StudyExperienceMode, ReadonlySet<string>>>> = {
  anki: new Set(['Anki mode']),
  mastery: new Set(['Mastery mode']),
  'free-revision': new Set(['Free revision']),
};

/**
 * Normalises labels generated by older default sessions without rewriting stored data.
 * Focus labels are learner-authored or selected context and therefore remain untouched.
 */
export function publicSessionLabel(session: Pick<StudySession, 'experienceMode' | 'mode' | 'label' | 'focus'>): string {
  const mode = session.experienceMode ?? (session.mode === 'practice' ? 'free-revision' : 'mastery');
  const presentation = studyModePresentation(mode);
  const stored = session.label?.trim();
  if (!stored) return presentation.label;
  if (!session.focus && LEGACY_GENERATED_LABELS[mode]?.has(stored)) return presentation.label;
  return stored;
}
